---10.What are the top 3 most purchased products within each category ?
WITH CTE AS
(
SELECT 
	category, 
	item_purchased,
	COUNT(item_purchased) AS most_purchased,
	RANK() OVER (PARTITION BY category ORDER BY COUNT(item_purchased) DESC) AS RNK
	FROM customer
	GROUP BY category, item_purchased
	)
SELECT * FROM CTE
WHERE RNK <= 3;

		-- Business Problem:
				--We do not know top products in each category.
		-- Impact:
				-- Helps identify best-selling products
				-- Supports better product placement
				-- Increases sales through focused promotions
