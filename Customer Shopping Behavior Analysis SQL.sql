---6.Average purchase: Standard vs Express shipping
SELECT 
	shipping_type,
	COUNT(DISTINCT customer_id) AS order_placed,
	ROUND(AVG(purchase_amount::NUMERIC),2) AS avg_purchase,
	ROUND(SUM(purchase_amount::NUMERIC),2) AS revenue
	FROM customer
	GROUP BY shipping_type
	ORDER BY revenue DESC;

		-- Business Problem: 
				--We do not know if fast shipping increases spending.
		-- Impact:
				-- Helps evaluate impact of shipping options on sales
				-- Supports better pricing for delivery services
				-- Encourages higher order value through faster delivery
