---11.Are customers who are repeat buyers (more than 5 previous purchases) also likely to subscribe ?
SELECT 
	CASE 
	WHEN previous_purchases > 5 THEN 'Repeat Buyers'
	ELSE 'Normal Buyers'
END AS customer_type,
subscription_status,
COUNT(*) AS customer_count,
COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (PARTITION BY CASE
	WHEN previous_purchases > 5 THEN 'Repeat Buyers'
	ELSE 'Normal Buyers'
	END
	) AS percents
FROM customer
GROUP BY CASE
	WHEN previous_purchases > 5 THEN 'Repeat Buyers'
	ELSE 'Normal Buyers'
	END, subscription_status;

		-- Business Problem: 
				--We do not know if loyal customers take subscriptions.
		-- Impact:
				-- Helps understand customer loyalty behavior
				-- Supports better subscription targeting
				-- Improves conversion to paid programs
