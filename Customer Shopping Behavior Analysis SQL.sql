---4.Which customer used a discount but still spent more then the average purchase amount ?
SELECT 
	customer_id,
	purchase_amount,
	discount_applied
	FROM customer
	WHERE discount_applied = 'Yes' AND purchase_amount > (SELECT AVG(purchase_amount) FROM customer)
	LIMIT 10;

			-- Business Problem: 
					--We cannot find customers who use discounts but still spend more.
		-- Impact:
					-- Helps identify high-value customers
					-- Enables smarter discount targeting
					-- Increases customer retention and revenue
