---12.What is the revenue contribution of each age group ?
SELECT 
	CASE
		WHEN age BETWEEN 18 AND 25 THEN '18-25'
		WHEN age BETWEEN 26 AND 35 THEN '26-35'
		WHEN age BETWEEN 36 AND 50 THEN '36-50'
		ELSE '51+'
	END AS age_group,
	ROUND(SUM(purchase_amount::NUMERIC),2) AS total_revenue
FROM customer
GROUP BY CASE
		WHEN age BETWEEN 18 AND 25 THEN '18-25'
		WHEN age BETWEEN 26 AND 35 THEN '26-35'
		WHEN age BETWEEN 36 AND 50 THEN '36-50'
		ELSE '51+'
	END
	ORDER BY total_revenue DESC;

		-- Business Problem:
				--We do not know which age group spends more.
		-- Impact:
				-- Helps identify high-value age groups
				-- Supports targeted marketing by age
				-- Improves campaign effectiveness
