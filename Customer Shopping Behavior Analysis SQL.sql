---1.Which category generates highest revenue?
SELECT category,
	ROUND(SUM(purchase_amount::NUMERIC),2) AS highest_revenue
	FROM customer
	GROUP BY category
	ORDER BY highest_revenue DESC;

		-- Business Problem: 
				--We do not know which category gives the most revenue.
		-- Impact:
				-- Helps identify top revenue categories
				-- Supports better inventory and stock decisions
				-- Improves focus in marketing and sales strategy
