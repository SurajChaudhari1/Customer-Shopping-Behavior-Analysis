---2.Are discounts actually increasing purchase value?
SELECT discount_applied,
	ROUND(SUM(purchase_amount::NUMERIC),2) AS highest_revenue,
	ROUND(AVG(purchase_amount::NUMERIC),2) AS average_purchase
	FROM customer
	GROUP BY discount_applied;

		-- Business Problem:
				--We do not know if discounts are helping or reducing profit.
		-- Impact:
				-- Helps measure real impact of discounts on sales
				-- Avoids unnecessary discount usage
				-- Improves overall profit margin
---------------------------------------------------------------------------------------------------------
